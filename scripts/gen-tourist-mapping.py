#!/usr/bin/env python3
"""Generates mapping/tourist.xml: all combinations of fmrel* keys and values produced by addfmreltags.pl
and the points, lines and areas of mapping/tourist-features.xml."""
import os, re, sys

SYMBOLY = ['cave', 'edu', 'education', 'interesting_object', 'local', 'major', 'none', 'peak', 'roundtrip',
           'ruin', 'shelter', 'spring', 'stripe', 'yes']
KCT = ['learning', 'alternative', 'horse', 'ski', 'bicycle', 'wheelchair']
BARVY = ['red', 'blue', 'green', 'yellow', 'black', 'white', 'default']
KLICE = []
for sit in ('', 'local', 'unknown'):
    KLICE += ['fmrelhiking%s%s' % (sit, b) for b in BARVY]
KLICE += ['fmrelhiking%s' % b for b in BARVY]
for typ in ('bicycle', 'mtb', 'horse', 'ski'):
    KLICE += ['fmrel%s%s' % (typ, b) for b in BARVY]
KLICE = list(dict.fromkeys(KLICE))
HLAVICKA = '''<?xml version="1.0" encoding="UTF-8"?>
<!-- Tag mapping for mapsforge-map-writer. The fmrel* keys are produced by addfmreltags.pl taken from Freemap Slovakia;
     the structure follows tag-mapping-fm.xml of mapsforge-freemap-hiking-style (https://github.com/FreemapSlovakia/mapsforge-freemap-hiking-style).
     Generated by scripts/gen-tourist-mapping.py from the fmrel* keys and mapping/tourist-features.xml. -->
<tag-mapping xmlns="http://mapsforge.org/tag-mapping" xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"
	xsi:schemaLocation="http://mapsforge.org/tag-mapping tag-mapping.xsd" default-zoom-appear="16" profile-name="default-profile">
'''
R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
with open(os.path.join(R, 'mapping', 'tourist-features.xml'), encoding='utf-8') as f:
    features = f.read()


def section(name):
    m = re.search(r'<%s>\n(.*?)\t</%s>' % (name, name), features, re.S)
    return m.group(1) if m else ''


with open(sys.argv[1] if len(sys.argv) > 1 else os.path.join(R, 'mapping', 'tourist.xml'), 'w', encoding='utf-8') as f:
    f.write(HLAVICKA)
    f.write('\t<pois>\n' + section('pois') + '\t</pois>\n\t<ways>\n')
    for k in KLICE:
        for v in SYMBOLY:
            f.write('\t\t<osm-tag key="%s" value="%s" zoom-appear="11" />\n' % (k, v))
    for b in ('red', 'blue', 'green', 'yellow'):
        for v in KCT:
            f.write('\t\t<osm-tag key="fmrelhiking%s" value="%s" zoom-appear="11" />\n' % (b, v))
    for v in ('edu', 'education'):
        f.write('\t\t<osm-tag key="fmreleducation" value="%s" zoom-appear="11" />\n' % v)
    f.write(section('ways'))
    f.write('\t</ways>\n</tag-mapping>\n')
